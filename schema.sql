-- Single source of truth for "may this email open this brief?".
create or replace function public.can_access_report(p_report public.reports, p_email text)
returns boolean
language plpgsql
security definer
set search_path = public
stable
as $$
declare
  c public.clients%rowtype;
  viewer_domain text;
begin
  if p_email is null or p_email = '' then
    return false;
  end if;
  viewer_domain := split_part(p_email, '@', 2);

  -- A block always wins.
  if exists (
    select 1 from public.report_access_blocks b
    where b.client_id = p_report.client_id and lower(b.email) = p_email
  ) then
    return false;
  end if;

  if public.is_admin() then
    return true;
  end if;

  -- Member of the owning client.
  if exists (
    select 1 from public.profiles pr
    where pr.id = auth.uid() and pr.client_id = p_report.client_id
  ) then
    return true;
  end if;

  -- Email domain matches the owning client's active domain.
  select * into c from public.clients where id = p_report.client_id;
  if found and c.status = 'active' and lower(c.domain) = viewer_domain then
    return true;
  end if;

  -- Explicit grant (e.g. an approved access request).
  if exists (
    select 1 from public.email_allowlist e
    where lower(e.email) = p_email and e.client_id = p_report.client_id and e.is_active
  ) then
    return true;
  end if;

  return false;
end;
$$;

-- Enforcement + logging chokepoint for shared links. Returns zero rows when denied,
-- which is what drives the "Request access" UI on the brief page.
create or replace function public.get_shared_report(p_token uuid)
returns setof public.reports
language plpgsql
security definer
set search_path = public
as $$
declare
  r public.reports%rowtype;
  viewer_email text;
begin
  if auth.uid() is null then
    return;
  end if;

  select * into r from public.reports where share_token = p_token limit 1;
  if not found then
    return;
  end if;

  viewer_email := lower(auth.jwt() ->> 'email');
  if not public.can_access_report(r, viewer_email) then
    return;
  end if;

  insert into public.report_access_log (report_id, client_id, user_id, email, accessed_via)
  values (r.id, r.client_id, auth.uid(), viewer_email, 'share_token');

  return next r;
end;
$$;

revoke all on function public.get_shared_report(uuid) from public;
grant execute on function public.get_shared_report(uuid) to authenticated;

