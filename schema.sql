-- Hard cap for free viewers: 3 questions + 3 notes per report/user.
-- Premium viewers are exempt via the profile flag.
create or replace function public.enforce_interaction_limits()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  existing_count integer;
  viewer_is_premium boolean := false;
begin
  if new.interaction_type not in ('question', 'note') then
    return new;
  end if;

  select coalesce(is_premium, false)
      or coalesce(c.exempt_from_freemium, false)
    into viewer_is_premium
  from public.profiles p
  left join public.clients c on c.id = p.client_id
  where p.id = new.user_id;

  if viewer_is_premium then
    return new;
  end if;

  select count(*)
    into existing_count
  from public.interactions
  where report_id = new.report_id
    and user_id = new.user_id
    and interaction_type = new.interaction_type;

  if existing_count >= 3 then
    raise exception 'interaction limit reached for %', new.interaction_type
      using errcode = 'check_violation';
  end if;

  return new;
end;
$$;

drop trigger if exists interaction_limits on public.interactions;
create trigger interaction_limits
  before insert on public.interactions
  for each row execute procedure public.enforce_interaction_limits();

